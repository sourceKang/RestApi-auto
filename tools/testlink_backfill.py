def catalog_records() -> Iterable[TestLinkCaseBackfill]:
    for raw in catalog_test_cases():
        case_ids = raw.get("case_ids") or []
        if not case_ids:
            continue
        name = str(raw.get("name") or case_ids[0])
        markers = [str(item) for item in raw.get("markers") or []]
        api_calls = [str(item).upper() for item in raw.get("api_call_prefixes") or []]
        validations = [str(item) for item in raw.get("validation_refs") or []]
        config_refs = [str(item) for item in raw.get("config_data_refs") or []]
        action = "Call the REST API according to the automation testcase flow."
        if api_calls:
            action = f"Execute API operations according to the automation testcase flow: {', '.join(api_calls)}."
        expected = "The API response satisfies the automation assertions."
        if validations:
            expected = f"The response satisfies the validation conditions: {', '.join(validations)}."
        preconditions = "The EMS REST API is reachable, and the test profile, hardware, and auth settings are configured."
        if config_refs:
            preconditions += f" Required configuration data: {', '.join(config_refs)}."

        yield TestLinkCaseBackfill(
            external_id=str(case_ids[0]),
            name=name,
            summary=f"Verify the `{name}` automation test flow.",
            preconditions=preconditions,
            steps=[
                TestLinkStep(1, "Prepare the session, target, and test data through pytest fixtures.", "The test prerequisites are complete."),
                TestLinkStep(2, action, expected),
                TestLinkStep(3, "Clean up test data when needed and output report metadata.", "The environment returns to a stable state, and the report can be traced to the testcase id."),
            ],
            source="cases.case_catalog",
            markers=markers,
        )


