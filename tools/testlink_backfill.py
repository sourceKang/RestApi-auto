@dataclass(frozen=True)
class TestLinkStep:
    step_number: int
    actions: str
    expected_results: str
    execution_type: int = 2


@dataclass(frozen=True)
class TestLinkCaseBackfill:
    external_id: str
    name: str
    summary: str
    preconditions: str
    steps: list[TestLinkStep]
    source: str
    markers: list[str]


def build_backfill_cases() -> list[TestLinkCaseBackfill]:
    cases_by_id: dict[str, TestLinkCaseBackfill] = {}
    for endpoint in [*READ_ENDPOINTS, *MUTATING_ENDPOINTS]:
        if endpoint.case_id:
            cases_by_id[endpoint.case_id] = endpoint_backfill(endpoint)

    for record in AUTOMATED_CASES:
        cases_by_id.setdefault(record.case_id, record_backfill(record))

    for case in catalog_records():
        cases_by_id.setdefault(case.external_id, case)

    for case in neox_records():
        cases_by_id[case.external_id] = case

    return sorted((collapse_case_steps(case) for case in cases_by_id.values()), key=case_sort_key)


def collapse_case_steps(case: TestLinkCaseBackfill) -> TestLinkCaseBackfill:
    """Keep one TestLink step row and put the ordered test flow inside the fields."""
    if len(case.steps) <= 1:
        return case
    actions = "\n".join(f"{index}. {step.actions}" for index, step in enumerate(case.steps, start=1))
    expected = "\n".join(
        f"{index}. {step.expected_results}" for index, step in enumerate(case.steps, start=1)
    )
    return TestLinkCaseBackfill(
        external_id=case.external_id,
        name=case.name,
        summary=case.summary,
        preconditions=case.preconditions,
        steps=[TestLinkStep(1, actions, expected)],
        source=case.source,
        markers=case.markers,
    )


def endpoint_backfill(case: EndpointCase) -> TestLinkCaseBackfill:
    method = case.method.upper()
    path = describe_path(case)
    has_payload = case.payload_factory is not None
    has_params = case.params_factory is not None
    is_mutating = method in {"POST", "PUT", "PATCH", "DELETE"}
    action_detail = f"Call `{method} {path}`."
    if has_params:
        action_detail += " Include the query parameters or filters defined by the automation."
    if has_payload:
        action_detail += " Include the request body generated by the automation payload factory."

    steps = [
        TestLinkStep(
            1,
            "Log in to the EMS REST API with the required role account and obtain a valid session.",
            "Login succeeds and a usable session id is returned.",
        ),
        TestLinkStep(
            2,
            action_detail,
            expected_success_text(case.expected_success),
        ),
    ]
    if is_mutating:
        steps.append(
            TestLinkStep(
                3,
                "If the test creates or changes data, clean up the test data through the automation cleanup or fixture flow.",
                "Cleanup completes without affecting later test cases or the existing environment state.",
            )
        )
    else:
        steps.append(
            TestLinkStep(
                3,
                "Parse the response JSON and verify the returned API content against the configured test target.",
                "The response JSON is parseable, and required fields or target data match the current test configuration.",
            )
        )

    return TestLinkCaseBackfill(
        external_id=str(case.case_id),
        name=case.name,
        summary=f"Verify the EMS REST API `{case.name}` endpoint behavior.",
        preconditions=standard_preconditions(case.domain, mutating=is_mutating),
        steps=steps,
        source="cases.endpoint_cases",
        markers=[case.domain, method.lower(), *([] if not is_mutating else ["mutating"])],
    )


def record_backfill(record: TestCaseRecord) -> TestLinkCaseBackfill:
    if record.domain == "session":
        return session_backfill(record)
    if record.domain == "permission":
        return permission_summary_backfill(record)
    if record.domain == "authmatrix":
        return auth_matrix_summary_backfill(record)
    if record.domain == "openapi":
        return openapi_backfill(record)
    if "invalid_param" in record.name or "invalid_parameters" in record.name:
        return invalid_param_backfill(record)

    return TestLinkCaseBackfill(
        external_id=record.case_id,
        name=record.name,
        summary=f"Verify the `{record.name}` automation test flow.",
        preconditions=standard_preconditions(record.domain, mutating="mutating" in record.markers),
        steps=[
            TestLinkStep(1, "Prepare the EMS REST API session and test data through the automation fixtures.", "The test prerequisites are prepared."),
            TestLinkStep(2, f"Execute the REST API operation covered by `{record.name}`.", "The API response satisfies the automation assertions."),
            TestLinkStep(3, "Record the Allure/reporting testcase metadata and test result.", "The report can be traced back to the corresponding testcase id."),
        ],
        source=record.source,
        markers=list(record.markers),
    )


